ALTER TABLE drama
  COMMENT = '短剧信息表',
  MODIFY COLUMN id BIGINT NOT NULL AUTO_INCREMENT COMMENT '剧目主键，自增编号',
  MODIFY COLUMN title VARCHAR(255) NOT NULL COMMENT '短剧名称',
  MODIFY COLUMN description VARCHAR(4000) NULL COMMENT '短剧简介',
  MODIFY COLUMN genre VARCHAR(255) NOT NULL COMMENT '短剧题材或分类',
  MODIFY COLUMN cover_url VARCHAR(2000) NOT NULL COMMENT '封面图片地址',
  MODIFY COLUMN status ENUM('DRAFT','PUBLISHED') NOT NULL COMMENT '发布状态';

ALTER TABLE episode
  COMMENT = '短剧分集表',
  MODIFY COLUMN id BIGINT NOT NULL AUTO_INCREMENT COMMENT '剧集主键，自增编号',
  MODIFY COLUMN drama_id BIGINT NOT NULL COMMENT '所属短剧 ID',
  MODIFY COLUMN episode_position INT NULL COMMENT '分集顺序，从 0 开始',
  MODIFY COLUMN title VARCHAR(255) NOT NULL COMMENT '剧集标题',
  MODIFY COLUMN video_url VARCHAR(2000) NOT NULL COMMENT '视频引用或播放地址',
  MODIFY COLUMN duration_seconds INT NOT NULL COMMENT '真实时长向上取整秒数',
  MODIFY COLUMN free BIT(1) NOT NULL COMMENT '是否免费';

ALTER TABLE seed_marker
  COMMENT = '演示数据初始化标记表',
  MODIFY COLUMN id VARCHAR(255) NOT NULL COMMENT '初始化任务唯一标识';

ALTER TABLE app_user
  COMMENT = '用户与管理员账号表',
  MODIFY COLUMN id BIGINT NOT NULL AUTO_INCREMENT COMMENT '用户主键，自增编号',
  MODIFY COLUMN username VARCHAR(64) NOT NULL COMMENT '唯一登录用户名',
  MODIFY COLUMN password_hash VARCHAR(100) NOT NULL COMMENT 'BCrypt 密码哈希',
  MODIFY COLUMN nickname VARCHAR(64) NOT NULL COMMENT '用户昵称',
  MODIFY COLUMN role ENUM('USER','ADMIN') NOT NULL COMMENT '用户角色';

ALTER TABLE interaction
  COMMENT = '观众评论与弹幕表',
  MODIFY COLUMN id BIGINT NOT NULL AUTO_INCREMENT COMMENT '互动主键，自增编号',
  MODIFY COLUMN type ENUM('COMMENT','DANMAKU') NOT NULL COMMENT '互动类型',
  MODIFY COLUMN text VARCHAR(500) NOT NULL COMMENT '互动正文',
  MODIFY COLUMN drama_id BIGINT NOT NULL COMMENT '所属短剧 ID',
  MODIFY COLUMN episode_id BIGINT NULL COMMENT '所属剧集 ID',
  MODIFY COLUMN at_seconds DOUBLE NULL COMMENT '弹幕出现时间，秒',
  MODIFY COLUMN lane INT NULL COMMENT '弹幕轨道 0 至 2',
  MODIFY COLUMN status ENUM('VISIBLE','HIDDEN') NOT NULL COMMENT '显示状态',
  MODIFY COLUMN user_id BIGINT NOT NULL COMMENT '发布者用户 ID',
  MODIFY COLUMN created_at DATETIME(6) NOT NULL COMMENT '创建时间';
